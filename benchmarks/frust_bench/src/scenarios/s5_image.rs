//! S5 — Image pipeline (decode-and-display stream while scrolling).
//!
//! Mirrors the Flutter side's `s5_image.dart`: a long virtualized stream
//! cycling [`S5_IMAGE_COUNT`] distinct generated images [`CYCLES`] times
//! (`s5ImageCount * 8` items total, matching Flutter's own item count), each
//! decoded off the UI thread and displayed once ready.
//!
//! # Dataset parity (ADDENDUM-binding)
//!
//! [`S5_IMAGE_SIZE`]/[`S5_IMAGE_COUNT`]/[`S5_IMAGE_SEED`] and
//! [`generate_s5_image_rgba`] are a byte-for-byte port of
//! `benchmarks/flutter_bench/lib/bench/datasets.dart`'s `s5ImageSize`/
//! `s5ImageCount`/`s5ImageSeed`/`generateS5ImageRgba`: the same
//! `SplitMix64(s5ImageSeed + index)` stream, the same per-pixel R = `(x*255)/
//! (size-1)` / G = `(y*255)/(size-1)` / B = `rng.nextByte()` / A = `0xFF`
//! construction. Per that module's own doc, the parity target is the
//! **pre-encode pixel content**, not the container bytes: the Flutter side
//! feeds these RGBA bytes straight into `ui.decodeImageFromPixels` (no
//! encoder on its fairness path at all), while this side wraps them in a
//! minimal in-process PNG (see [`encode_png_rgba8`]) so it can exercise the
//! real [`frust::decode_image_async`] PNG/JPEG-decode path the scenario is
//! named for — the encoder differs by necessity (an `image`-crate PNG vs. no
//! container at all), the decoded pixels do not.
//!
//! # Why a hand-rolled minimal PNG encoder
//!
//! `frust::decode_image_async` only accepts encoded PNG/JPEG bytes (it wraps
//! `ImageSource::decode`, which wraps `image::load_from_memory`) — there is no
//! raw-pixel async decode entry point in the facade, unlike Flutter's
//! `ui.decodeImageFromPixels`. Encoding a real PNG normally means adding the
//! `image` crate as a dependency, but this task's file scope is this module
//! only (`benchmarks/frust_bench/src/scenarios/s5_image.rs`) — no `Cargo.toml`
//! edit. [`encode_png_rgba8`] is instead a small, self-contained,
//! dependency-free PNG encoder: an uncompressed (DEFLATE "stored" blocks)
//! `IHDR`/`IDAT`/`IEND` chunk stream with a real zlib wrapper and CRC32/Adler-32
//! checksums — everything `image`'s PNG decoder needs, produced with nothing
//! beyond `std`. It exists purely to round-trip our own generated bytes back
//! through the real decode path; it is not a general-purpose encoder.
//!
//! # Why a hand-rolled virtualized stream instead of `frust::ListView`
//!
//! Same reasoning as S2 (see that module's doc): `ListView` has no
//! programmatic scroll-to/controller API, so a scripted (no-real-input)
//! auto-scroll must drive its own offset during paint — and, like S2, must
//! **publish that offset through a signal** so the next rebuild reports
//! `ChangeFlags::LAYOUT` and the cell window re-windows as it scrolls, even
//! under Android's layout-skip frame gate (`docs/ARCHITECTURE.md`'s Frame gate;
//! without it, layout runs only on frame 1 on device, the window freezes, no
//! new image ids become visible to decode, and the scene goes empty). This
//! scenario reuses
//! the real `frust::Image`/`ImageView` leaf widget per visible cell (built and
//! driven directly through the public `frust_core` `View`/`Widget`/`BuildCtx`/
//! `LayoutCtx`/`PaintCtx` API — the same pattern `frust-widgets`' own
//! containers use internally), so the actual GPU image-composite path is
//! identical to using `Image` anywhere else in the framework; only the
//! windowing/scroll-driving is reimplemented.
//!
//! # Decode scheduling
//!
//! A nested [`frust::Component`] ([`ImageStreamPage`]) holds one
//! [`frust::UseTask`] per **unique image id** (`0..S5_IMAGE_COUNT`, not per
//! stream item — the same image recurs every [`S5_IMAGE_COUNT`] items, so it
//! is decoded once and reused, mirroring `ImageSource`'s documented
//! decode-once contract), lazily started the first time that id enters the
//! materialized window. The widget reports its currently-visible image ids
//! back to the component via an `RwSignal` written during layout — the same
//! paint/layout-time signal-publish idiom S2 and `BubbleChartWidget`'s FPS
//! readout use, since layout/paint carry no `EventCtx`/application state to
//! drive a callback with.

