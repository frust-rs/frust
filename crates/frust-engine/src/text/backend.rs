/// What one glyph run cost the frame.
///
/// Purely observational, in the same spirit as [`CompiledFrame`]'s own
/// counters: nothing downstream branches on either number, and they exist so
/// "a glyph the engine cannot paint is a missing glyph, not a wrong one" is
/// measurable from outside the sink rather than asserted about it.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub(crate) struct GlyphRunOutcome {
    /// Glyphs that became a recorded draw.
    ///
    /// One per *glyph*, not per draw: a colour glyph costs one draw per layer
    /// and still counts once here, which is what keeps this bounded by the
    /// run's own glyph count.
    pub(crate) drawn: u32,
    /// Glyphs the sink refused to draw — a bitmap glyph, a stroked one, or a
    /// colour glyph whose layers have no exact engine spelling.
    pub(crate) skipped: u32,
    /// Whether the run was drawn out of the resident-run cache, without
    /// reaching `glifo` at all (see [`EngineGlyphSink::draw_resident`]).
    pub(crate) resident: bool,
}

/// The paint a drawing command arriving at the sink is painted with.
#[derive(Debug, Clone)]
enum SinkPaint {
    /// The run's own brush, as encoded once by the compiler.
    Run,
    /// A COLR layer's own palette colour or gradient, which the layer it
    /// paints is encoded from when the glyph closes.
    Layer(Brush),
    /// A glyph resolved out of the atlas: the image `glifo` built from the
    /// slot, whose source is the handle [`EngineGlyphSink::atlas_image_source`]
    /// answered with.
    Atlas(Image),
    /// A paint set by `glifo` that this backend has no encoding for — an
    /// uncached bitmap glyph's pixmap.
    Unsupported,
}

/// The sink state `glifo` saves and restores around each glyph.
///
/// `glifo` brackets every glyph it draws in a `save_state`/`restore_state`
/// pair, so the transform, paint transform and paint it sets inside the
/// bracket must not leak into the next glyph. Restoring is a whole-value
/// assignment rather than a field-by-field undo, which is what makes that
/// impossible to get half-right.
#[derive(Debug, Clone)]
pub(crate) struct GlyphSinkState {
    /// Maps the drawing command's geometry into device space.
    transform: Affine,
    /// The paint transform relative to [`Self::transform`], as `glifo`
    /// computes it per glyph.
    paint_transform: Affine,
    /// Which paint the next drawing command is painted with.
    paint: SinkPaint,
    /// The tint an atlas-sampled glyph is drawn through, as `glifo` set it.
    ///
    /// Part of the saved state rather than a bare field because `glifo` sets it
    /// *inside* the save/restore bracket it draws a cached glyph in, so a
    /// restore has to take it back with everything else — the same rule the
    /// transform and the paint follow.
    tint: Option<Tint>,
}

/// One cached glyph held back while its run is still being drawn, carrying
/// everything either lowering needs: a [quad](GlyphQuad) if the whole run
/// turns out resident, the general image draw otherwise.
#[derive(Debug, Clone)]
pub(crate) struct PendingGlyphQuad {
    /// The atlas paint `glifo` set for the glyph.
    image: Image,
    /// The rectangle `glifo` filled, in the space of [`Self::transform`].
    area: Rect,
    /// The draw transform `glifo` set for the glyph.
    transform: Affine,
    /// The paint transform relative to [`Self::transform`].
    paint_transform: Affine,
    /// The tint the glyph is drawn through.
    tint: Option<Tint>,
    /// The slot the paint names.
    slot: AtlasSlot,
}

impl PendingGlyphQuad {
    /// The device rectangle `[x0, y0, x1, y1]` this glyph covers when it can be
    /// a quad, or `None` when only the general image draw paints it exactly.
    ///
    /// A quad samples slot texel `k` at device pixel `x0 + k` with no transform
    /// and no extend mode, which is the general draw's own answer exactly when:
    /// the paint samples nearest (a bilinear or bicubic one blends texels); the
    /// draw transform is a translation by whole pixels with no relative paint
    /// transform on top (anything else moves texel centres off pixel centres);
    /// and the rectangle is the slot's own extent from its origin (so no pixel
    /// reaches past the slot, where the general draw's pad extend would clamp).
    /// `glifo` draws every cached outline glyph that way; a bitmap glyph samples
    /// bilinearly and a COLR one is placed fractionally, and both take the
    /// general draw.
    fn quad_rect(&self) -> Option<[i64; 4]> {
        if self.image.sampler.quality != ImageQuality::Low
            || self.paint_transform != Affine::IDENTITY
        {
            return None;
        }
        let [a, b, c, d, tx, ty] = self.transform.as_coeffs();
        if a != 1.0 || b != 0.0 || c != 0.0 || d != 1.0 || !whole_pixel(tx) || !whole_pixel(ty) {
            return None;
        }
        let width = f64::from(self.slot.width);
        let height = f64::from(self.slot.height);
        if self.area != Rect::new(0.0, 0.0, width, height) {
            return None;
        }
        // Exact: both are whole numbers well inside `i64` (see `whole_pixel`).
        let (x0, y0) = (tx as i64, ty as i64);
        Some([
            x0,
            y0,
            x0 + i64::from(self.slot.width),
            y0 + i64::from(self.slot.height),
        ])
    }
}

/// Whether `value` is a whole pixel coordinate a device rectangle can start at.
///
/// Bounded far outside any device grid so the conversion to `i64` is exact;
/// a glyph that far away is culled either way.
fn whole_pixel(value: f64) -> bool {
    value.fract() == 0.0 && on_quad_grid(value)
}

/// Whether `value` lies inside the bound [`whole_pixel`] holds a quad corner
/// to — the half of it a coordinate already known to be whole still has to
/// pass.
fn on_quad_grid(value: f64) -> bool {
    value.is_finite() && value.abs() <= f64::from(1_u32 << 30)
}

