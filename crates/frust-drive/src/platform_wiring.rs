//! Points a generated project's Android and iOS host projects at the native
//! modules shipped inside the crates cargo resolves for it: the embeddings in
//! the shell crates, and the Gradle modules and Swift packages of every
//! plugin the project depends on.
//!
//! The Android embedding is a Gradle library module in
//! `frust-shell-android/platform/android/frust-embedding`, the iOS one a Swift
//! package in `frust-shell-ios/platform/ios/FrustEmbedding`; a plugin's live
//! under its own package (`frust-iap/platform/android`,
//! `frust-iap/platform/ios/FrustIap`). Where those crates live depends on how
//! the project depends on the framework — a checkout's crate directory under
//! `--frust-path`, the unpacked release under cargo's registry cache
//! otherwise — and moves whenever the resolved version does (`cargo update`)
//! or the project moves to another machine. So no location is ever written
//! into a tracked file: [`sync`] asks [`crate::packages`] (one `cargo
//! metadata` run) and writes the answers into the two machine-local places
//! the host build tools read them from:
//!
//! - `android/local.properties` (gitignored): [`EMBEDDING_DIR_KEY`] and one
//!   [`plugin_module_key`] per plugin Gradle module, each an absolute module
//!   directory. The generated `settings.gradle.kts` resolves every
//!   `projectDir` through its `frustLocalDir(key)` helper, which fails naming
//!   `frust run`/`frust build` when the file or key is missing.
//! - one symlink per local Swift package next to `Runner.xcodeproj`
//!   (`ios/FrustEmbedding`, `ios/FrustIap`, …, all gitignored), which the
//!   project's package references name by the relative path
//!   `FrustEmbedding`, `FrustIap`, ….
//!
//! Idempotent: an up-to-date project is left byte-identical, and the returned
//! [`Report`] says per module what (if anything) changed. A project without
//! an `android/` or `ios/` directory is skipped for that platform, and cargo is
//! not asked about a package only a skipped platform needs.

