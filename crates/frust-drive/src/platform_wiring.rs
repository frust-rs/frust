/// The package shipping the Android embedding module.
pub const ANDROID_SHELL_PACKAGE: &str = "frust-shell-android";
/// The package shipping the iOS embedding Swift package.
pub const IOS_SHELL_PACKAGE: &str = "frust-shell-ios";
/// The Android embedding module's directory inside [`ANDROID_SHELL_PACKAGE`].
pub const ANDROID_EMBEDDING_REL: &str = "platform/android/frust-embedding";
/// The iOS embedding package's directory inside [`IOS_SHELL_PACKAGE`].
pub const IOS_EMBEDDING_REL: &str = "platform/ios/FrustEmbedding";
/// The `android/local.properties` key `settings.gradle.kts` resolves the
/// `:frust-embedding` module directory from.
pub const EMBEDDING_DIR_KEY: &str = "frust.embedding.dir";
/// The project-relative path of the machine-local properties file [`sync`]
/// keeps every Android module directory in.
pub const LOCAL_PROPERTIES: &str = "android/local.properties";
/// The project-relative path of the tracked Gradle properties file. It
/// carries no machine path in a project generated today; one generated by an
/// earlier template may still hold [`EMBEDDING_DIR_KEY`] there for its
/// `settings.gradle.kts` to read, and [`sync`] keeps that existing value
/// current rather than strand the project (it never adds the key).
pub const GRADLE_PROPERTIES: &str = "android/gradle.properties";
/// The project-relative path of the symlink the iOS project's embedding
/// package reference (`relativePath = "FrustEmbedding"`) resolves through.
pub const IOS_EMBEDDING_LINK: &str = "ios/FrustEmbedding";

/// The `android/local.properties` key holding plugin Gradle module
/// `gradle_name`'s directory: `frust.plugin.frust-iap.dir` for `:frust-iap`.
pub fn plugin_module_key(gradle_name: &str) -> String {
    format!("frust.plugin.{}.dir", gradle_name.trim_start_matches(':'))
}

/// The project-relative path of the symlink a local Swift package's
/// reference (`relativePath = "<package_name>"`) resolves through:
/// `ios/FrustIap` for `FrustIap`.
pub fn swift_package_link(package_name: &str) -> String {
    format!("ios/{package_name}")
}

/// Why the wiring could not be brought up to date.
#[derive(Debug, thiserror::Error)]
pub enum SyncError {
    /// cargo could not say where a shell or plugin crate lives.
    #[error("could not locate the frust shell and plugin crates: {0}")]
    Locate(#[from] PackagesError),
    /// The located crate does not carry the native directory it should — an
    /// incomplete package, which Gradle or Xcode would otherwise report far
    /// less clearly.
    #[error(
        "`{package}` resolved to '{}', which has no native module at '{}'",
        package_dir.display(),
        embedding_dir.display()
    )]
    EmbeddingMissing {
        package: &'static str,
        package_dir: PathBuf,
        embedding_dir: PathBuf,
    },
    /// Reading or writing a project file failed.
    #[error("{action} '{}': {source}", path.display())]
    Io {
        action: &'static str,
        path: PathBuf,
        source: io::Error,
    },
}

/// What [`sync`] did for one location.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Wiring {
    /// The project has no directory for this platform (or, for
    /// [`Report::legacy_gradle_property`], no such key to refresh).
    Skipped,
    /// Already pointed at `target`; nothing was written.
    Unchanged { target: PathBuf },
    /// Now points at `target`. `previous` is the value or link target it
    /// replaced, `None` when the key or link did not exist yet.
    Updated {
        target: PathBuf,
        previous: Option<String>,
    },
    /// `path` exists but is not a symlink (a vendored copy, say) — user
    /// content, so it is left alone.
    Occupied { path: PathBuf, target: PathBuf },
    /// This host could not create the symlink (no symlink support, or a
    /// Windows account without the privilege). The rest of the sync stands.
    Unsupported { target: PathBuf, reason: String },
}

impl Wiring {
    /// Whether this location was written.
    pub fn changed(&self) -> bool {
        matches!(self, Self::Updated { .. })
    }
}

/// One plugin native module's wiring in a [`Report`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ModuleWiring {
    /// The plugin's registry id (`"iap"`).
    pub plugin_id: &'static str,
    /// The module wired.
    pub module: NativeModule,
    /// What happened to its key or link.
    pub wiring: Wiring,
}

/// The outcome of one [`sync`]: the two embeddings, every plugin module, and
/// the legacy `gradle.properties` key.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Report {
    /// The Android embedding's [`EMBEDDING_DIR_KEY`] in [`LOCAL_PROPERTIES`].
    pub android: Wiring,
    /// The iOS embedding's [`IOS_EMBEDDING_LINK`].
    pub ios: Wiring,
    /// One entry per plugin Gradle module / Swift package wired, in registry
    /// order.
    pub plugins: Vec<ModuleWiring>,
    /// [`EMBEDDING_DIR_KEY`] in [`GRADLE_PROPERTIES`], refreshed only where an
    /// earlier template put it; [`Wiring::Skipped`] when absent.
    pub legacy_gradle_property: Wiring,
}

impl Report {
    fn skipped() -> Self {
        Self {
            android: Wiring::Skipped,
            ios: Wiring::Skipped,
            plugins: Vec::new(),
            legacy_gradle_property: Wiring::Skipped,
        }
    }

    /// Whether anything was written.
    pub fn changed(&self) -> bool {
        self.android.changed()
            || self.ios.changed()
            || self.legacy_gradle_property.changed()
            || self.plugins.iter().any(|m| m.wiring.changed())
    }

    /// One human-readable line per location that was written or needs
    /// attention; empty when nothing changed and nothing is wrong. Skipped
    /// and unchanged locations say nothing.
    pub fn lines(&self) -> Vec<String> {
        let mut lines = Vec::new();
        let android = match (&self.legacy_gradle_property, &self.android) {
            (Wiring::Updated { target, .. }, _) => Some(format!(
                "Android embedding: {GRADLE_PROPERTIES} -> {} (kept for this project's older \
                 settings.gradle.kts; {LOCAL_PROPERTIES} carries it too)",
                target.display()
            )),
            (_, wiring) => describe("Android embedding", LOCAL_PROPERTIES, wiring),
        };
        lines.extend(android);
        lines.extend(describe("iOS embedding", IOS_EMBEDDING_LINK, &self.ios));
        for module in &self.plugins {
            let (label, location) = match module.module.kind {
                NativeKind::GradleModule { gradle_name } => (
                    format!("Android module `{gradle_name}`"),
                    LOCAL_PROPERTIES.to_string(),
                ),
                NativeKind::SwiftPackage { package_name } => (
                    format!("iOS package `{package_name}`"),
                    swift_package_link(package_name),
                ),
            };
            lines.extend(describe(&label, &location, &module.wiring));
        }
        lines
    }
}

fn describe(label: &str, location: &str, wiring: &Wiring) -> Option<String> {
    match wiring {
        Wiring::Skipped | Wiring::Unchanged { .. } => None,
        Wiring::Updated { target, .. } => {
            Some(format!("{label}: {location} -> {}", target.display()))
        }
        Wiring::Occupied { path, target } => Some(format!(
            "{label}: '{}' is not a symlink, left as is (expected a link to '{}')",
            path.display(),
            target.display()
        )),
        Wiring::Unsupported { target, reason } => Some(format!(
            "{label}: could not link {location} -> '{}': {reason}",
            target.display()
        )),
    }
}

/// Where `project_dir`'s Android and iOS embeddings resolve, without writing
/// anything — what [`sync`] would point the project at. Both are located
/// whether or not the project has the platform's directory, so a report (the
/// CLI's `doctor`) can show them for any project.
pub fn resolve(
    locator: &dyn PackageLocator,
    project_dir: &Path,
) -> Result<EmbeddingDirs, SyncError> {
    let dirs = locator.locate_many(project_dir, &[ANDROID_SHELL_PACKAGE, IOS_SHELL_PACKAGE])?;
    let [android, ios]: [PathBuf; 2] =
        dirs.try_into()
            .map_err(|dirs: Vec<PathBuf>| PackagesError::MetadataUnreadable {
                project_dir: project_dir.to_path_buf(),
                reason: format!("expected 2 package directories, got {}", dirs.len()),
            })?;
    Ok(EmbeddingDirs {
        android: native_dir(ANDROID_SHELL_PACKAGE, &android, ANDROID_EMBEDDING_REL)?,
        ios: native_dir(IOS_SHELL_PACKAGE, &ios, IOS_EMBEDDING_REL)?,
    })
}

/// The embedding directories [`resolve`] found.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EmbeddingDirs {
    /// The Android embedding Gradle module.
    pub android: PathBuf,
    /// The iOS embedding Swift package.
    pub ios: PathBuf,
}

/// Brings `project_dir`'s Android and iOS wiring up to date with the crates
/// `cargo metadata` resolves for it (`--locked` when the project has a
/// `Cargo.lock`).
pub fn sync(project_dir: &Path) -> Result<Report, SyncError> {
    sync_with(&CargoLocator::new(&RealProcessRunner), project_dir)
}

/// [`sync`] through an injected locator.
///
/// Every package — the shell crate of each present platform and every
/// installed plugin's package with a module for one — is located in one
/// [`PackageLocator::locate_many`] call, and every native directory is
/// verified before anything is written, so a failure leaves the project as
/// it was.
pub fn sync_with(locator: &dyn PackageLocator, project_dir: &Path) -> Result<Report, SyncError> {
    let has_android = project_dir.join("android").is_dir();
    let has_ios = project_dir.join("ios").is_dir();
    let mut report = Report::skipped();
    if !has_android && !has_ios {
        return Ok(report);
    }

    let modules: Vec<(&'static str, NativeModule)> = installed_native_modules(project_dir)
        .into_iter()
        .filter(|(_, module)| match module.kind {
            NativeKind::GradleModule { .. } => has_android,
            NativeKind::SwiftPackage { .. } => has_ios,
        })
        .collect();

    let mut packages: Vec<&'static str> = Vec::new();
    if has_android {
        packages.push(ANDROID_SHELL_PACKAGE);
    }
    if has_ios {
        packages.push(IOS_SHELL_PACKAGE);
    }
    for (_, module) in &modules {
        if !packages.contains(&module.package) {
            packages.push(module.package);
        }
    }
    let package_dirs = locator.locate_many(project_dir, &packages)?;
    let package_dir = |package: &str| -> &Path {
        let at = packages
            .iter()
            .position(|p| *p == package)
            .expect("every wanted package was located");
        &package_dirs[at]
    };

    let android_target = has_android
        .then(|| {
            native_dir(
                ANDROID_SHELL_PACKAGE,
                package_dir(ANDROID_SHELL_PACKAGE),
                ANDROID_EMBEDDING_REL,
            )
        })
        .transpose()?;
    let ios_target = has_ios
        .then(|| {
            native_dir(
                IOS_SHELL_PACKAGE,
                package_dir(IOS_SHELL_PACKAGE),
                IOS_EMBEDDING_REL,
            )
        })
        .transpose()?;
    let mut module_targets = Vec::with_capacity(modules.len());
    for (_, module) in &modules {
        module_targets.push(native_dir(
            module.package,
            package_dir(module.package),
            module.dir_in_package,
        )?);
    }

    let mut module_wirings: Vec<Option<Wiring>> = vec![None; modules.len()];
    if let Some(target) = android_target {
        let mut entries = vec![(EMBEDDING_DIR_KEY.to_string(), target.clone())];
        let mut slots = Vec::new();
        for (at, ((_, module), module_target)) in modules.iter().zip(&module_targets).enumerate() {
            if let NativeKind::GradleModule { gradle_name } = module.kind {
                entries.push((plugin_module_key(gradle_name), module_target.clone()));
                slots.push(at);
            }
        }
        let mut written = write_properties(
            &project_dir.join(LOCAL_PROPERTIES),
            &entries,
            Missing::Append,
        )?
        .into_iter();
        report.android = written.next().expect("one change per entry");
        for (at, wiring) in slots.into_iter().zip(written) {
            module_wirings[at] = Some(wiring);
        }
        report.legacy_gradle_property = write_properties(
            &project_dir.join(GRADLE_PROPERTIES),
            &[(EMBEDDING_DIR_KEY.to_string(), target)],
            Missing::Skip,
        )?
        .remove(0);
    }
    if let Some(target) = ios_target {
        report.ios = link_dir(&project_dir.join(IOS_EMBEDDING_LINK), &target)?;
        for (at, ((_, module), module_target)) in modules.iter().zip(&module_targets).enumerate() {
            if let NativeKind::SwiftPackage { package_name } = module.kind {
                let link = project_dir.join(swift_package_link(package_name));
                module_wirings[at] = Some(link_dir(&link, module_target)?);
            }
        }
    }

    report.plugins = modules
        .into_iter()
        .zip(module_wirings)
        .map(|((plugin_id, module), wiring)| ModuleWiring {
            plugin_id,
            module,
            wiring: wiring.expect("every module belongs to a present platform"),
        })
        .collect();
    Ok(report)
}

/// Every native module of every registry plugin `project_dir`'s `Cargo.toml`
/// depends on (a `[dependencies]` entry by name or `package = …`, either
/// dependency form, never an `optional` one — cargo leaves a disabled
/// optional dependency out of the resolve, so it could not be located),
/// paired with its plugin's id. Base and optional-feature modules alike: an
/// unused key or link is harmless, a missing one fails the build. An
/// unreadable or unparseable manifest names no plugin — the locate that
/// follows reports the manifest problem itself.
fn installed_native_modules(project_dir: &Path) -> Vec<(&'static str, NativeModule)> {
    let Ok(text) = fs::read_to_string(project_dir.join("Cargo.toml")) else {
        return Vec::new();
    };
    let Ok(doc) = text.parse::<DocumentMut>() else {
        return Vec::new();
    };
    known_plugins()
        .into_iter()
        .filter(|spec| plugin_is_installed(spec, &doc))
        .flat_map(|spec| {
            spec.native_modules()
                .into_iter()
                .map(move |module| (spec.id, module))
        })
        .collect()
}

/// Whether `module`'s machine-local slot — its `local.properties` key or its
/// `ios/` link — exists at all in `project_dir`, whatever it points at.
pub(crate) fn module_slot_present(project_dir: &Path, module: &NativeModule) -> bool {
    match module.kind {
        NativeKind::GradleModule { gradle_name } => local_properties::read_value(
            &project_dir.join(LOCAL_PROPERTIES),
            &plugin_module_key(gradle_name),
        )
        .ok()
        .flatten()
        .is_some(),
        NativeKind::SwiftPackage { package_name } => {
            fs::symlink_metadata(project_dir.join(swift_package_link(package_name))).is_ok()
        }
    }
}

/// Writes each `(module, directory)` into `project_dir`'s machine-local
/// wiring — Gradle modules as [`plugin_module_key`] entries in one
/// [`LOCAL_PROPERTIES`] merge, Swift packages as [`swift_package_link`]
/// symlinks — returning one [`Wiring`] per module in order. The plugin-add
/// counterpart of [`sync`] for modules just added; it neither locates nor
/// verifies the directories (its caller does).
pub(crate) fn wire_modules(
    project_dir: &Path,
    modules: &[(NativeModule, PathBuf)],
) -> Result<Vec<Wiring>, SyncError> {
    let mut wirings: Vec<Option<Wiring>> = vec![None; modules.len()];
    let mut entries = Vec::new();
    let mut slots = Vec::new();
    for (at, (module, dir)) in modules.iter().enumerate() {
        match module.kind {
            NativeKind::GradleModule { gradle_name } => {
                entries.push((plugin_module_key(gradle_name), dir.clone()));
                slots.push(at);
            }
            NativeKind::SwiftPackage { package_name } => {
                let link = project_dir.join(swift_package_link(package_name));
                wirings[at] = Some(link_dir(&link, dir)?);
            }
        }
    }
    if !entries.is_empty() {
        let written = write_properties(
            &project_dir.join(LOCAL_PROPERTIES),
            &entries,
            Missing::Append,
        )?;
        for (at, wiring) in slots.into_iter().zip(written) {
            wirings[at] = Some(wiring);
        }
    }
    Ok(wirings
        .into_iter()
        .map(|w| w.expect("one wiring per module"))
        .collect())
}

/// `rel` under `package_dir`, verified to exist and made absolute and
/// canonical, so the value written does not depend on the directory a build
/// tool resolves it from.
fn native_dir(package: &'static str, package_dir: &Path, rel: &str) -> Result<PathBuf, SyncError> {
    let dir = package_dir.join(rel);
    if !dir.is_dir() {
        return Err(SyncError::EmbeddingMissing {
            package,
            package_dir: package_dir.to_path_buf(),
            embedding_dir: dir,
        });
    }
    Ok(host_path::canonicalize_simplified(&dir).unwrap_or(dir))
}

/// Merges `entries` (keys to directories, rendered forward-slashed) into the
/// properties file at `path`, one [`Wiring`] per entry.
fn write_properties(
    path: &Path,
    entries: &[(String, PathBuf)],
    missing: Missing,
) -> Result<Vec<Wiring>, SyncError> {
    let values: Vec<String> = entries
        .iter()
        .map(|(_, target)| host_path::to_portable_string(target))
        .collect();
    let pairs: Vec<(&str, &str)> = entries
        .iter()
        .zip(&values)
        .map(|((key, _), value)| (key.as_str(), value.as_str()))
        .collect();
    let changes =
        local_properties::merge(path, &pairs, missing).map_err(|source| SyncError::Io {
            action: "updating",
            path: path.to_path_buf(),
            source,
        })?;
    Ok(changes
        .into_iter()
        .zip(entries)
        .map(|(change, (_, target))| match change {
            Change::Unchanged => Wiring::Unchanged {
                target: target.clone(),
            },
            Change::Set { previous } => Wiring::Updated {
                target: target.clone(),
                previous,
            },
            Change::Absent => Wiring::Skipped,
        })
        .collect())
}

/// Points the symlink at `link` to `target`: created when absent, replaced
/// when it points elsewhere, left alone when it already points there (the
/// two compared after [`host_path::same_path`]'s normalisation, so a
/// Windows verbatim or differently-cased read-back still matches) or when
/// `link` is a real file or directory.
fn link_dir(link: &Path, target: &Path) -> Result<Wiring, SyncError> {
    let previous = match fs::symlink_metadata(link) {
        Err(err) if err.kind() == io::ErrorKind::NotFound => None,
        Err(source) => {
            return Err(SyncError::Io {
                action: "inspecting",
                path: link.to_path_buf(),
                source,
            });
        }
        Ok(meta) if !meta.file_type().is_symlink() => {
            return Ok(Wiring::Occupied {
                path: link.to_path_buf(),
                target: target.to_path_buf(),
            });
        }
        Ok(_) => {
            let current = fs::read_link(link).map_err(|source| SyncError::Io {
                action: "reading the symlink",
                path: link.to_path_buf(),
                source,
            })?;
            if host_path::same_path(&current, target) {
                return Ok(Wiring::Unchanged {
                    target: target.to_path_buf(),
                });
            }
            remove_link(link).map_err(|source| SyncError::Io {
                action: "replacing the symlink",
                path: link.to_path_buf(),
                source,
            })?;
            Some(current.display().to_string())
        }
    };

    match create_dir_link(target, link) {
        Ok(()) => Ok(Wiring::Updated {
            target: target.to_path_buf(),
            previous,
        }),
        Err(err) if is_unsupported(&err) => Ok(Wiring::Unsupported {
            target: target.to_path_buf(),
            reason: err.to_string(),
        }),
        Err(source) => Err(SyncError::Io {
            action: "creating the symlink",
            path: link.to_path_buf(),
            source,
        }),
    }
}

#[cfg(unix)]
fn create_dir_link(target: &Path, link: &Path) -> io::Result<()> {
    std::os::unix::fs::symlink(target, link)
}

#[cfg(windows)]
fn create_dir_link(target: &Path, link: &Path) -> io::Result<()> {
    std::os::windows::fs::symlink_dir(target, link)
}

#[cfg(not(any(unix, windows)))]
fn create_dir_link(_target: &Path, _link: &Path) -> io::Result<()> {
    Err(io::Error::new(
        io::ErrorKind::Unsupported,
        "this platform has no symlinks",
    ))
}

/// A directory symlink is removed as a directory on Windows and as a file
/// everywhere else.
fn remove_link(link: &Path) -> io::Result<()> {
    if cfg!(windows) {
        fs::remove_dir(link).or_else(|_| fs::remove_file(link))
    } else {
        fs::remove_file(link)
    }
}

/// Whether a symlink-creation failure means "this host cannot do it" rather
/// than a fault in the project: no symlink support at all, or Windows'
/// `ERROR_PRIVILEGE_NOT_HELD` (1314) for an account without Developer Mode.
fn is_unsupported(err: &io::Error) -> bool {
    err.kind() == io::ErrorKind::Unsupported || (cfg!(windows) && err.raw_os_error() == Some(1314))
}

