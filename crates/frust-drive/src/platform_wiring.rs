    const IAP_ANDROID_REL: &str = "platform/android";
    const IAP_IOS_REL: &str = "platform/ios/FrustIap";

    const LOCAL: &str = "sdk.dir=/opt/android-sdk\r\n# a comment\nfrust.versionName=1.0\n";

    /// A project with `android/` (holding an Android-Studio-style
    /// [`LOCAL`] and a template `gradle.properties` without the key) and
    /// `ios/`, depending on no plugin.
    fn project(root: &Path) -> PathBuf {
        let project = root.join("app");
        fs::create_dir_all(project.join("android")).unwrap();
        fs::create_dir_all(project.join("ios/Runner.xcodeproj")).unwrap();
        fs::write(project.join(LOCAL_PROPERTIES), LOCAL).unwrap();
        fs::write(
            project.join(GRADLE_PROPERTIES),
            "org.gradle.jvmargs=-Xmx2048m\nandroid.useAndroidX=true\n",
        )
        .unwrap();
        fs::write(
            project.join("Cargo.toml"),
            "[package]\nname = \"app\"\n\n[dependencies]\n\
             frust = { package = \"frust-ui\", version = \"0.5.0\" }\n",
        )
        .unwrap();
        project
    }

    /// [`project`] depending on `frust-iap` in `form`.
    fn project_with_iap(root: &Path, form: &str) -> PathBuf {
        let project = project(root);
        let manifest = project.join("Cargo.toml");
        let text = fs::read_to_string(&manifest).unwrap();
        fs::write(&manifest, format!("{text}{form}\n")).unwrap();
        project
    }

    #[cfg(unix)]
    #[test]
    fn sync_writes_local_properties_and_links_the_ios_package() {
        let root = temp_dir("fresh");
        let (android, ios, _, stub) = checkout(&root);
        let project = project(&root);
        let gradle_before = fs::read(project.join(GRADLE_PROPERTIES)).unwrap();

        let report = sync_with(&stub, &project).unwrap();
        let android_target = android.join(ANDROID_EMBEDDING_REL);
        let ios_target = ios.join(IOS_EMBEDDING_REL);
        assert_eq!(
            report.android,
            Wiring::Updated {
                target: android_target.clone(),
                previous: None,
            }
        );
        assert_eq!(
            report.ios,
            Wiring::Updated {
                target: ios_target.clone(),
                previous: None,
            }
        );
        assert_eq!(report.legacy_gradle_property, Wiring::Skipped);
        assert!(report.plugins.is_empty());
        assert!(report.changed());

        // Every existing byte, CRLF ending included, is kept; the key is
        // appended. The tracked gradle.properties is not touched at all.
        assert_eq!(
            fs::read_to_string(project.join(LOCAL_PROPERTIES)).unwrap(),
            format!("{LOCAL}frust.embedding.dir={}\n", android_target.display())
        );
        assert_eq!(
            fs::read(project.join(GRADLE_PROPERTIES)).unwrap(),
            gradle_before
        );
        assert_eq!(
            fs::read_link(project.join(IOS_EMBEDDING_LINK)).unwrap(),
            ios_target
        );

        let lines = report.lines();
        assert_eq!(lines.len(), 2, "{lines:?}");
        assert!(lines[0].starts_with("Android embedding: android/local.properties -> "));
        assert!(lines[1].starts_with("iOS embedding: ios/FrustEmbedding -> "));
        let _ = fs::remove_dir_all(&root);
    }

    /// A plugin the manifest depends on — in either dependency form, or
    /// renamed — gets its Gradle module key and its Swift package link, all
    /// from the one `locate_many` call.
    #[cfg(unix)]
    #[test]
    fn installed_plugins_get_their_keys_and_links() {
        for form in [
            "frust-iap = \"0.5.0\"",
            "frust-iap = { version = \"0.5.0\" }",
            "store = { package = \"frust-iap\", path = \"../plugins/iap\" }",
        ] {
            let root = temp_dir("plugins");
            let (_, _, iap, stub) = checkout(&root);
            let project = project_with_iap(&root, form);

            let report = sync_with(&stub, &project).unwrap();
            assert_eq!(stub.calls(), 1, "{form}");
            let android_dir = iap.join(IAP_ANDROID_REL);
            let ios_dir = iap.join(IAP_IOS_REL);
            let wired: Vec<(&str, &Wiring)> = report
                .plugins
                .iter()
                .map(|m| (m.plugin_id, &m.wiring))
                .collect();
            assert_eq!(
                wired,
                [
                    (
                        "iap",
                        &Wiring::Updated {
                            target: android_dir.clone(),
                            previous: None
                        }
                    ),
                    (
                        "iap",
                        &Wiring::Updated {
                            target: ios_dir.clone(),
                            previous: None
                        }
                    ),
                ],
                "{form}"
            );
            assert_eq!(
                local_properties::read_value(
                    &project.join(LOCAL_PROPERTIES),
                    "frust.plugin.frust-iap.dir"
                )
                .unwrap(),
                Some(android_dir.display().to_string())
            );
            assert_eq!(
                fs::read_link(project.join("ios/FrustIap")).unwrap(),
                ios_dir
            );
            let lines = report.lines();
            assert_eq!(lines.len(), 4, "{lines:?}");
            assert!(
                lines[2].starts_with("Android module `:frust-iap`: android/local.properties -> "),
                "{lines:?}"
            );
            assert!(
                lines[3].starts_with("iOS package `FrustIap`: ios/FrustIap -> "),
                "{lines:?}"
            );
            let _ = fs::remove_dir_all(&root);
        }
    }

