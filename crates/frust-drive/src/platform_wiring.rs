    /// `wire_modules` (the plugin-add path) writes the same key and link
    /// `sync` would, and reports an already-current slot unchanged.
    #[cfg(unix)]
    #[test]
    fn wire_modules_writes_keys_and_links_for_the_given_modules() {
        let root = temp_dir("wire-modules");
        let (_, _, iap, _) = checkout(&root);
        let project = project(&root);
        let iap_spec = known_plugins()
            .into_iter()
            .find(|spec| spec.id == "iap")
            .unwrap();
        let modules: Vec<(NativeModule, PathBuf)> = iap_spec
            .native_modules()
            .into_iter()
            .map(|m| (m, iap.join(m.dir_in_package)))
            .collect();
        assert_eq!(modules.len(), 2);
        assert!(
            modules
                .iter()
                .all(|(m, _)| !module_slot_present(&project, m))
        );

        let first = wire_modules(&project, &modules).unwrap();
        assert!(first.iter().all(Wiring::changed), "{first:?}");
        assert!(
            modules
                .iter()
                .all(|(m, _)| module_slot_present(&project, m))
        );
        assert_eq!(
            fs::read_link(project.join("ios/FrustIap")).unwrap(),
            iap.join(IAP_IOS_REL)
        );
        let second = wire_modules(&project, &modules).unwrap();
        assert!(
            second.iter().all(|w| matches!(w, Wiring::Unchanged { .. })),
            "{second:?}"
        );
        let _ = fs::remove_dir_all(&root);
    }

