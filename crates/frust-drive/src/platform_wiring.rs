    /// What `cargo update` does to a registry project: the crates resolve
    /// somewhere new, and the next sync follows them — keys and links alike.
    #[cfg(unix)]
    #[test]
    fn a_moved_package_replaces_the_values_and_the_links() {
        let root = temp_dir("moved");
        let (old_android, old_ios, _, stub) = checkout(&root.join("old"));
        let project = project_with_iap(&root, "frust-iap = \"0.5.0\"");
        sync_with(&stub, &project).unwrap();

        let (android, ios, iap, moved) = checkout(&root.join("new"));
        let report = sync_with(&moved, &project).unwrap();
        assert_eq!(
            report.ios,
            Wiring::Updated {
                target: ios.join(IOS_EMBEDDING_REL),
                previous: Some(old_ios.join(IOS_EMBEDDING_REL).display().to_string()),
            }
        );
        assert_eq!(
            report.android,
            Wiring::Updated {
                target: android.join(ANDROID_EMBEDDING_REL),
                previous: Some(
                    old_android
                        .join(ANDROID_EMBEDDING_REL)
                        .display()
                        .to_string()
                ),
            }
        );
        assert!(report.plugins.iter().all(|m| m.wiring.changed()));
        assert_eq!(
            fs::read_link(project.join("ios/FrustIap")).unwrap(),
            iap.join(IAP_IOS_REL)
        );
        let properties = fs::read_to_string(project.join(LOCAL_PROPERTIES)).unwrap();
        assert_eq!(properties.matches("frust.embedding.dir=").count(), 1);
        assert_eq!(properties.matches("frust.plugin.frust-iap.dir=").count(), 1);
        assert!(properties.starts_with(LOCAL), "{properties}");
        let _ = fs::remove_dir_all(&root);
    }

    /// A value carrying `java.util.Properties` specials — a Windows drive
