//! The shared mock dataset the whole Huddle app renders (PLAN.md's
//! "All data mocked/static").
//!
//! This is a **hub file finalized in the skeleton (task 10)** — Phase C screen
//! tasks READ this dataset through the accessor functions below but never edit
//! this module (see `src/README-phase-c.md`). It is plain `&'static`/const data
//! plus accessor `fn`s that materialize owned [`User`]/[`Channel`]/[`Dm`]/
//! [`Message`]/[`ActivityItem`] values; there is **no reactive state here** —
//! controllers (Phase C) own the signals, seeding them from these accessors.
//!
//! # Shape (per PLAN)
//!
//! - 10 [`users`] (name, initials, [`UserStatus`]).
//! - 6 [`channels`], one of them [`Channel::private`].
//! - 9 [`dms`] (each a 1:1 conversation with a [`User`]) — one of them
//!   (`dm-9`) deliberately carries no messages, so the channel feed's
//!   empty-conversation state ("No messages yet — say hi") has a real
//!   destination (task 22's empty-states audit; the frozen-hub rule is lifted
//!   for this one addition).
//! - ~40 [`messages`] spread across the channels (varied: text lengths, a
//!   link, a file stub, reactions).
//! - one 120-message channel ([`FIREHOSE_ID`], `#firehose`) for pagination,
//!   generated by [`firehose_messages`].
//! - an [`activity`] feed derived from the messages that mention the current
//!   user ([`CURRENT_USER_ID`]).

/// A member's presence state (the status dot in avatars and roster rows).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UserStatus {
    /// Available.
    Online,
    /// Idle / away.
    Away,
    /// Do not disturb.
    Dnd,
}

impl UserStatus {
    /// A short human label for the status.
    pub fn label(self) -> &'static str {
        match self {
            UserStatus::Online => "Online",
            UserStatus::Away => "Away",
            UserStatus::Dnd => "Do not disturb",
        }
    }
}

/// A workspace member.
#[derive(Clone, Copy, Debug)]
pub struct User {
    /// Stable numeric id (used in `/user/:id` deep links).
    pub id: u32,
    /// Display name.
    pub name: &'static str,
    /// Two-letter initials for the avatar escape-hatch paint.
    pub initials: &'static str,
    /// Presence.
    pub status: UserStatus,
}

/// A channel (a named, possibly private, multi-member conversation).
#[derive(Clone, Copy, Debug)]
pub struct Channel {
    /// Stable string id (used in `/channel/:id`).
    pub id: &'static str,
    /// Display name (without the leading `#`).
    pub name: &'static str,
    /// Whether the channel is private (rendered with a lock icon).
    pub private: bool,
    /// One-line channel topic.
    pub topic: &'static str,
}

/// A direct message conversation (1:1 with a [`User`]).
#[derive(Clone, Copy, Debug)]
pub struct Dm {
    /// Stable string id (used in `/channel/:id`, DMs route through the same
    /// feed screen as channels).
    pub id: &'static str,
    /// The other participant.
    pub user_id: u32,
    /// A short preview of the latest message (roster subtitle).
    pub preview: &'static str,
}

/// The body of a [`Message`] — text, a link preview stub, or a file stub.
#[derive(Clone, Copy, Debug)]
pub enum MessageBody {
    /// Plain text (may include an `@mention`).
    Text(&'static str),
    /// A link with a preview title (a `Card`-rendered link preview in Phase C).
    Link {
        /// The URL.
        url: &'static str,
        /// A human title for the preview card.
        title: &'static str,
    },
    /// A file attachment stub (no real bytes — a non-goal per PLAN).
    File {
        /// The file name.
        name: &'static str,
        /// A human size string (e.g. `"2.4 MB"`).
        size: &'static str,
    },
}

/// A single emoji reaction with a count.
#[derive(Clone, Copy, Debug)]
pub struct Reaction {
    /// The emoji (color-glyph rendering is a Phase A/C item).
    pub emoji: &'static str,
    /// How many members reacted.
    pub count: u32,
}

/// A message in a channel or DM.
#[derive(Clone, Copy, Debug)]
pub struct Message {
    /// Stable numeric id.
    pub id: u32,
    /// The channel or DM this message belongs to.
    pub channel_id: &'static str,
    /// The author.
    pub author_id: u32,
    /// The message body.
    pub body: MessageBody,
    /// Reactions attached to the message.
    pub reactions: &'static [Reaction],
}

/// An item in the Activity tab — a mention derived from the message stream.
#[derive(Clone, Copy, Debug)]
pub struct ActivityItem {
    /// The message that produced this activity item.
    pub message_id: u32,
    /// The channel the mention happened in.
    pub channel_id: &'static str,
    /// Who mentioned the current user.
    pub author_id: u32,
    /// The mention text.
    pub text: &'static str,
}

/// The "me" user whose mentions drive the [`activity`] feed.
pub const CURRENT_USER_ID: u32 = 1;

/// The id of the 120-message pagination channel (`#firehose`).
pub const FIREHOSE_ID: &str = "firehose";

/// How many messages the [`FIREHOSE_ID`] channel holds (the pagination target).
pub const FIREHOSE_COUNT: u32 = 120;

