/// The rotating text bodies the [`firehose_messages`] generator cycles through.
const FIREHOSE_BODIES: [&str; 6] = [
    "deploy started",
    "deploy finished",
    "health check passed",
    "cache warmed",
    "metrics flushed",
    "@Ada Lovelace nightly build is green",
];

// ---------------------------------------------------------------------------
// Accessors (materialize owned values — no reactive state)
// ---------------------------------------------------------------------------

/// All 10 workspace members, in roster order.
pub fn users() -> Vec<User> {
    USERS.to_vec()
}

/// Look up a member by id.
pub fn user(id: u32) -> Option<User> {
    USERS.iter().copied().find(|u| u.id == id)
}

/// All 6 channels (one of which is [`Channel::private`]).
pub fn channels() -> Vec<Channel> {
    CHANNELS.to_vec()
}

/// Look up a channel by id.
pub fn channel(id: &str) -> Option<Channel> {
    CHANNELS.iter().copied().find(|c| c.id == id)
}

/// All 9 direct-message conversations (one, `dm-9`, carries no messages).
pub fn dms() -> Vec<Dm> {
    DMS.to_vec()
}

/// Every authored channel/DM message (the 40 static ones; the firehose's 120
/// are materialized on demand by [`firehose_messages`]/[`messages_for`]).
pub fn messages() -> Vec<Message> {
    MESSAGES.to_vec()
}

/// All messages in a given channel or DM, oldest-first. For [`FIREHOSE_ID`]
/// this generates the 120-message pagination stream.
pub fn messages_for(channel_id: &str) -> Vec<Message> {
    if channel_id == FIREHOSE_ID {
        return firehose_messages();
    }
    MESSAGES
        .iter()
        .copied()
        .filter(|m| m.channel_id == channel_id)
        .collect()
}

/// The 120-message `#firehose` channel, generated for the pagination demo.
///
/// Ids start at 1000 so they never collide with the authored [`MESSAGES`].
pub fn firehose_messages() -> Vec<Message> {
    (0..FIREHOSE_COUNT)
        .map(|i| {
            let author = USERS[(i as usize) % USERS.len()].id;
            let body = FIREHOSE_BODIES[(i as usize) % FIREHOSE_BODIES.len()];
            Message {
                id: 1000 + i,
                channel_id: FIREHOSE_ID,
                author_id: author,
                body: MessageBody::Text(body),
                reactions: NO_REACTIONS,
            }
        })
        .collect()
}

/// The Activity feed: every message (authored channels + firehose) whose text
/// body mentions the current user ([`CURRENT_USER_ID`]).
pub fn activity() -> Vec<ActivityItem> {
    let me = user(CURRENT_USER_ID).map(|u| u.name).unwrap_or_default();
    let mention = format!("@{me}");
    messages()
        .into_iter()
        .chain(firehose_messages())
        .filter_map(|m| match m.body {
            MessageBody::Text(text) if text.contains(&mention) => Some(ActivityItem {
                message_id: m.id,
                channel_id: m.channel_id,
                author_id: m.author_id,
                text,
            }),
            _ => None,
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dataset_matches_the_plan_shape() {
        assert_eq!(users().len(), 10, "10 users");
        assert_eq!(channels().len(), 6, "6 channels");
        assert_eq!(
            channels().iter().filter(|c| c.private).count(),
            1,
            "exactly one private channel",
        );
        assert_eq!(dms().len(), 9, "9 DMs (one an empty DM — task 22)");
        assert_eq!(messages().len(), 40, "~40 authored messages");
    }

    #[test]
    fn dm_9_is_the_empty_conversation() {
        assert!(
            dms().iter().any(|d| d.id == "dm-9"),
            "dm-9 is in the roster"
        );
        assert!(
            messages_for("dm-9").is_empty(),
            "dm-9 carries no messages (drives the empty-feed state — task 22)"
        );
    }

    #[test]
    fn firehose_channel_has_120_messages() {
        assert_eq!(firehose_messages().len(), FIREHOSE_COUNT as usize);
        assert_eq!(messages_for(FIREHOSE_ID).len(), 120);
    }

    #[test]
    fn every_message_and_dm_references_a_real_user_and_channel() {
        let channel_ids: Vec<&str> = channels().iter().map(|c| c.id).collect();
        let dm_ids: Vec<&str> = dms().iter().map(|d| d.id).collect();
        for m in messages() {
            assert!(user(m.author_id).is_some(), "author {} exists", m.author_id);
            let known = channel_ids.contains(&m.channel_id) || dm_ids.contains(&m.channel_id);
            assert!(
                known,
                "message channel {} is a real channel or DM",
                m.channel_id
            );
        }
        for d in dms() {
            assert!(user(d.user_id).is_some(), "DM peer {} exists", d.user_id);
        }
    }

    #[test]
    fn activity_feed_is_derived_from_mentions() {
        let feed = activity();
        assert!(
            !feed.is_empty(),
            "the current user is mentioned at least once"
        );
        let me = user(CURRENT_USER_ID).unwrap().name;
        let mention = format!("@{me}");
        for item in feed {
            assert!(
                item.text.contains(&mention),
                "each activity item is a mention"
            );
        }
    }
}
